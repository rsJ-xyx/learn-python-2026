if __name__ == "__main__":
    import random
    random.seed(42)

    for n in (0, 1, 5, 50):
        data = random.sample(range(1000), n)
        expect = sorted(data)
        assert insertion_sort(data.copy()) == expect, f"插入排序 n={n}"
        assert merge_sort(data.copy()) == expect, f"归并排序 n={n}"
        assert quick_sort(data.copy()) == expect, f"快速排序 n={n}"

    assert insertion_sort([3, 3, 1, 1, 2]) == [1, 1, 2, 3, 3], "有重复元素时要能处理"
    assert merge_sort([]) == []

